// /api/poios — ποιος είναι συνδεδεμένος αυτή τη στιγμή.
//
// Το Cloudflare Access ξέρει ήδη ποιος μπήκε: κουβαλάει το email σε
// κάθε αίτημα, και το διαβάζουμε για το μήνυμα του commit. Αυτό εδώ
// απλώς το λέει και στη σελίδα.
//
// ΓΙΑΤΙ ΤΟ ΘΕΛΟΥΜΕ
//
// Η υπογραφή του άρθρου γίνεται σελίδα δημοσιογράφου. Όσο ο συντάκτης
// πληκτρολογεί το όνομά του κάθε φορά, αργά ή γρήγορα θα το γράψει
// αλλιώς — και τότε έχουμε δύο σελίδες για τον ίδιο άνθρωπο. Με το
// email ξέρουμε ποιος είναι χωρίς να τον ρωτήσουμε, και το όνομα
// γράφεται μία μόνο φορά στη ζωή του λογαριασμού.
//
// ΔΕΝ είναι έλεγχος ασφαλείας. Όλο το /api/ κάθεται πίσω από το
// Access· χωρίς έγκυρο εισιτήριο δεν φτάνει εδώ αίτημα. Εμείς
// διαβάζουμε ένα όνομα, δεν φυλάμε πόρτα.
//
// Αν λείπει το email — τοπικά με τον serve.js, ή αν το Access δεν
// περάσει κεφαλίδα — γυρίζει κενό. Η σελίδα το δέχεται και δείχνει τη
// λίστα με τα γνωστά ονόματα· δεν σταματά τίποτα.
import { whoFrom } from '../../admin-store.js';

export function onRequestGet({ request }) {
  return new Response(JSON.stringify({ email: whoFrom(request) }), {
    headers: {
      'Content-Type': 'application/json; charset=utf-8',
      'Cache-Control': 'no-store',
    },
  });
}
